import httpx
import json
from typing import Dict, List, Optional
from sqlalchemy.orm import Session
from app.models.incident import Incident
from app.models.asset import Asset
from app.models.monitoring import MonitoringResult
from datetime import datetime, timedelta

class AITroubleshooter:
    """
    AI-Assisted Incident Troubleshooting
    
    Uses local Ollama LLM to analyze incidents.
    Clearly distinguishes:
    - Observed Facts (from monitoring data)
    - Possible Causes (hypotheses)
    - Recommended Troubleshooting Steps (actions)
    """

    def __init__(self, db: Session, ollama_url: str = "http://localhost:11434", model: str = "llama3.2"):
        self.db = db
        self.ollama_url = ollama_url
        self.model = model

    def analyze_incident(self, incident_id: int) -> Dict:
        """Analyze an incident and return structured troubleshooting"""
        incident = self.db.query(Incident).filter(Incident.id == incident_id).first()
        if not incident:
            return {"error": "Incident not found"}

        asset = self.db.query(Asset).filter(Asset.id == incident.asset_id).first()
        if not asset:
            return {"error": "Asset not found"}

        # Gather monitoring context
        context = self._gather_context(incident, asset)
        
        # Generate AI analysis
        analysis = self._generate_analysis(incident, asset, context)
        
        return {
            "incident_id": incident.incident_id,
            "asset": {
                "hostname": asset.hostname,
                "ip": asset.ip_address,
                "type": asset.asset_type.value,
                "criticality": asset.criticality.value,
                "production_line": asset.production_line
            },
            "observed_facts": analysis.get("observed_facts", []),
            "possible_causes": analysis.get("possible_causes", []),
            "recommended_steps": analysis.get("recommended_steps", []),
            "confidence": analysis.get("confidence", "low"),
            "disclaimer": "This analysis is generated by AI based on available monitoring data. It represents hypotheses, not confirmed diagnoses. Always verify before taking action.",
            "generated_at": datetime.utcnow().isoformat()
        }

    def _gather_context(self, incident: Incident, asset: Asset) -> Dict:
        """Gather all relevant monitoring data for the incident"""
        # Recent monitoring results for this asset
        recent_results = self.db.query(MonitoringResult).filter(
            MonitoringResult.asset_id == asset.id,
            MonitoringResult.checked_at > datetime.utcnow() - timedelta(hours=24)
        ).order_by(MonitoringResult.checked_at.desc()).limit(50).all()

        # Related incidents on same production line
        related_incidents = []
        if asset.production_line:
            related_assets = self.db.query(Asset).filter(
                Asset.production_line == asset.production_line,
                Asset.id != asset.id,
                Asset.is_active == True
            ).all()
            for ra in related_assets:
                ri = self.db.query(Incident).filter(
                    Incident.asset_id == ra.id,
                    Incident.status.in_(['OPEN', 'INVESTIGATING', 'IN_PROGRESS'])
                ).first()
                if ri:
                    related_incidents.append({
                        "asset": ra.hostname,
                        "incident": ri.incident_id,
                        "severity": ri.severity.value
                    })

        return {
            "asset": {
                "hostname": asset.hostname,
                "ip": asset.ip_address,
                "type": asset.asset_type.value,
                "criticality": asset.criticality.value,
                "production_line": asset.production_line,
                "location": asset.location
            },
            "incident": {
                "id": incident.incident_id,
                "category": incident.category.value,
                "severity": incident.severity.value,
                "title": incident.title,
                "description": incident.description,
                "detected_at": incident.detected_at.isoformat()
            },
            "monitoring_results": [
                {
                    "check_type": r.check_type.value,
                    "result": r.result.value,
                    "response_time_ms": r.response_time_ms,
                    "packet_loss_percent": r.packet_loss_percent,
                    "message": r.message,
                    "checked_at": r.checked_at.isoformat()
                }
                for r in recent_results
            ],
            "related_incidents": related_incidents
        }

    def _generate_analysis(self, incident: Incident, asset: Asset, context: Dict) -> Dict:
        """Generate AI analysis using Ollama"""
        prompt = self._build_prompt(incident, asset, context)
        
        try:
            response = httpx.post(
                f"{self.ollama_url}/api/generate",
                json={
                    "model": self.model,
                    "prompt": prompt,
                    "stream": False,
                    "format": "json",
                    "options": {
                        "temperature": 0.3,
                        "top_p": 0.9
                    }
                },
                timeout=60.0
            )
            
            if response.status_code == 200:
                result = response.json()
                try:
                    return json.loads(result.get("response", "{}"))
                except json.JSONDecodeError:
                    pass
        except Exception as e:
            pass
        
        # Fallback: deterministic analysis based on rules
        return self._fallback_analysis(context)

    def _build_prompt(self, incident: Incident, asset: Asset, context: Dict) -> str:
        return f"""You are an IT Operations Senior Engineer. Analyze this incident and provide structured troubleshooting.

INCIDENT: {incident.incident_id}
- Asset: {asset.hostname} ({asset.ip_address})
- Type: {asset.asset_type.value}
- Criticality: {asset.criticality.value}
- Production Line: {asset.production_line or 'N/A'}
- Location: {asset.location or 'N/A'}
- Category: {incident.category.value}
- Severity: {incident.severity.value}
- Title: {incident.title}
- Description: {incident.description}
- Detected: {incident.detected_at}

RECENT MONITORING RESULTS:
{json.dumps(context['monitoring_results'][:20], indent=2)}

RELATED INCIDENTS ON SAME PRODUCTION LINE:
{json.dumps(context['related_incidents'], indent=2)}

You MUST respond with valid JSON in this exact format:
{{
  "observed_facts": [
    "Fact 1 from monitoring data",
    "Fact 2 from monitoring data"
  ],
  "possible_causes": [
    {{"cause": "Possible cause 1", "likelihood": "high|medium|low", "reasoning": "Why this is likely"}},
    {{"cause": "Possible cause 2", "likelihood": "medium", "reasoning": "Why this is likely"}}
  ],
  "recommended_steps": [
    {{"step": 1, "action": "Specific action to take", "command": "Optional command to run", "priority": "immediate|soon|later"}},
    {{"step": 2, "action": "Next action", "command": "Optional command", "priority": "soon"}}
  ],
  "confidence": "low|medium|high"
}}

Rules:
- Only use facts from the monitoring data above
- Distinguish clearly between OBSERVED FACTS and POSSIBLE CAUSES
- Never state a hypothesis as a fact
- Prioritize steps by impact and ease of execution
- If production line is affected, note the business impact"""

    def _fallback_analysis(self, context: Dict) -> Dict:
        """Deterministic fallback when AI is unavailable"""
        facts = []
        causes = []
        steps = []

        asset = context['asset']
        incident = context['incident']
        results = context['monitoring_results']

        # Collect observed facts
        icmp_results = [r for r in results if r['check_type'] == 'icmp']
        tcp_results = [r for r in results if r['check_type'] == 'tcp']
        http_results = [r for r in results if r['check_type'] == 'http']

        if icmp_results:
            offline_count = sum(1 for r in icmp_results if r['result'] == 'TIMEOUT' or r['result'] == 'FAILURE')
            if offline_count > 0:
                facts.append(f"ICMP ping failing for {asset['hostname']} ({offline_count} recent failures)")

            avg_latency = sum(r.get('response_time_ms', 0) for r in icmp_results if r.get('response_time_ms')) / max(1, len([r for r in icmp_results if r.get('response_time_ms')]))
            if avg_latency > 100:
                facts.append(f"High average latency: {avg_latency:.0f}ms")

            avg_loss = sum(r.get('packet_loss_percent', 0) for r in icmp_results if r.get('packet_loss_percent') is not None) / max(1, len([r for r in icmp_results if r.get('packet_loss_percent') is not None]))
            if avg_loss > 5:
                facts.append(f"Packet loss detected: {avg_loss:.1f}% average")

        if tcp_results:
            closed = [r for r in tcp_results if r['result'] == 'FAILURE']
            if closed:
                ports = list(set(r['status_code'] for r in closed))
                facts.append(f"TCP ports closed: {ports}")

        if http_results:
            failed = [r for r in http_results if r['result'] == 'FAILURE']
            if failed:
                facts.append(f"HTTP health checks failing: {len(failed)} failures")

        # Determine possible causes based on facts
        if any("ICMP ping failing" in f for f in facts):
            causes.append({"cause": "Network connectivity loss to host", "likelihood": "high", "reasoning": "ICMP timeout indicates host unreachable or firewall blocking"})
            causes.append({"cause": "Host powered off or OS crashed", "likelihood": "medium", "reasoning": "Complete ping failure suggests host down"})
            causes.append({"cause": "Network switch/port issue", "likelihood": "medium", "reasoning": "Could be upstream network problem"})
        
        if any("Packet loss" in f for f in facts):
            causes.append({"cause": "Network congestion or link degradation", "likelihood": "high", "reasoning": "Packet loss typically indicates link issues"})
            causes.append({"cause": "Faulty cable or switch port", "likelihood": "medium", "reasoning": "Physical layer problems cause packet loss"})

        if any("TCP ports closed" in f for f in facts):
            causes.append({"cause": "Service not running on target host", "likelihood": "high", "reasoning": "Port closed means no listener"})
            causes.append({"cause": "Firewall blocking ports", "likelihood": "medium", "reasoning": "Host firewall or network ACL may block access"})

        if asset.get('production_line'):
            causes.append({"cause": "Production line network segment issue", "likelihood": "medium", "reasoning": f"Multiple assets on {asset['production_line']} may share network path"})

        # Generate recommended steps
        step = 1
        if any("ICMP ping failing" in f for f in facts):
            steps.append({"step": step, "action": f"Verify {asset['hostname']} power and OS status", "command": f"ping {asset['ip']}", "priority": "immediate"})
            step += 1
            steps.append({"step": step, "action": "Check upstream switch port status", "command": "show interface status", "priority": "immediate"})
            step += 1

        if any("Packet loss" in f for f in facts):
            steps.append({"step": step, "action": "Run extended ping test to measure loss pattern", "command": f"ping -n 50 {asset['ip']}", "priority": "immediate"})
            step += 1
            steps.append({"step": step, "action": "Check switch port counters for errors", "command": "show interfaces counters errors", "priority": "soon"})
            step += 1

        if any("TCP ports closed" in f for f in facts):
            steps.append({"step": step, "action": "Verify target service is running on host", "command": "systemctl status <service> or services.msc", "priority": "immediate"})
            step += 1
            steps.append({"step": step, "action": "Check firewall rules on host and network", "priority": "soon"})
            step += 1

        if asset.get('production_line'):
            steps.append({"step": step, "action": f"Check other assets on {asset['production_line']} for similar issues", "priority": "soon"})
            step += 1

        steps.append({"step": step, "action": "Review recent network changes or deployments", "priority": "later"})

        return {
            "observed_facts": facts if facts else ["No recent monitoring data available"],
            "possible_causes": causes if causes else [{"cause": "Unknown - insufficient data", "likelihood": "low", "reasoning": "Need more monitoring history"}],
            "recommended_steps": steps if steps else [{"step": 1, "action": "Gather more diagnostic data", "priority": "immediate"}],
            "confidence": "medium"
        }